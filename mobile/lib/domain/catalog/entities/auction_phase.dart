/// طور المزاد **كما يقوله الخادم** — وهو ما تُبنى عليه تبويبات الرئيسية.
///
/// ثلاث قيم لا ستّ: `AuctionStatus` في المخطط حالةُ الكيان الكاملة (مسودة،
/// ملغى، مسوّى…) ويحتاجها من يدير المزاد؛ وهذا ما يراه المتصفّح. الاشتقاق
/// بينهما قرارُ خادم يعيش في `apps/auctions/states.py`، وحسابه هنا يجعل
/// لـ«منتهي» تعريفاً ثانياً يفترق عن الأصل عند أول حالة جديدة (المادة ٤-٥).
///
/// **ولهذا لا يستنتج التطبيق الطور من الوقت.** مقارنة `auctionEndsAt` بساعة
/// الجهاز تبدو كافية وليست: ساعة العميل ليست ساعة الخادم، وهي بعينها العلّة
/// التي أظهرت في v1 «انتهى» لمزادٍ ما زال مفتوحاً لمن ساعته متقدّمة.
enum AuctionPhase {
  /// مجدول ولم يبدأ.
  upcoming('upcoming'),

  /// جارٍ الآن.
  active('active'),

  /// انتهى أو سُوّي.
  ended('ended'),

  /// طورٌ لم يعرفه هذا الإصدار.
  ///
  /// المادتان ٢-٣ و٣-٥: قيمة لم نرها من قبل تُحفظ ولا تُسقط الاستجابة. مركبةٌ
  /// بطورٍ مجهول تُعرض ولا تختفي، ولا يُقال عنها «منتهية» — الجهل ليس نفياً.
  unknown('');

  const AuctionPhase(this.slug);

  /// الاسم على السلك وفي `?phase=` على العنوان — نصٌّ واحد للمعنى الواحد.
  final String slug;

  /// التبويبات الثلاثة بترتيب عرضها. `unknown` ليس تبويباً: لا أحد يطلب
  /// «وريني ما لا أفهمه».
  static const List<AuctionPhase> tabs = <AuctionPhase>[
    upcoming,
    active,
    ended,
  ];

  /// التبويب الافتراضي حين يأتي العنوان بلا `?phase=` أو بقيمة لا نعرفها.
  ///
  /// «نشط» لا «قريباً»: المزاد واحد في الأسبوع، والسؤال الأول لمن يفتح التطبيق
  /// هو «إيش المفتوح دلوقتي؟». وحين لا يكون هناك نشط تقول الحالة الفارغة ذلك،
  /// وعدّادا التبويبين الآخرين ظاهران فيعرف أين يذهب.
  static const AuctionPhase defaultTab = active;

  /// يقرأ التبويب من العنوان. رابطٌ من إصدارٍ أحدث يفتح الافتراضي ولا يُسقط
  /// الشاشة — عنوانٌ مشارَك يجب أن يفتح شيئاً.
  static AuctionPhase fromSlug(String? slug) =>
      tabs.firstWhere((phase) => phase.slug == slug, orElse: () => defaultTab);
}
