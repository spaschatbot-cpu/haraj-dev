/// رموز الأخطاء التي **يتفرّع** عليها التطبيق برمجياً.
///
/// الرمز هنا لا يُعرض ولا يُترجم — الرسالة العربية تأتي من الخادم دائماً
/// (انظر `failure.dart`). القائمة قصيرة عمداً: لا تُذكر هنا إلا حالة يتغيّر
/// بها **سلوك** الشاشة، لا مجرد نصّها. أي رمز آخر يصل من الخادم يُعرض برسالته
/// ولا يحتاج سطراً هنا، ولذلك ليست هذه مرآة لرموز الفيز 007.
///
/// **القيم منسوخة من الخادم حرفياً** (`apps/accounts/errors.py` و
/// `apps/bidding/services.py`): الرمز عقد بين الطرفين، وحرف زائد هنا يعني فرعاً
/// لا يُفعَّل أبداً — وهو أسوأ من غياب الفرع لأنه يبدو موجوداً.
library;

abstract final class FailureCodes {
  /// المزايدة أقل من الحالية وتحتاج تأكيداً صريحاً (409 ثم إعادة إرسال بتأكيد).
  static const String bidLowerNeedsConfirmation = 'lower_needs_confirm';

  /// تجاوز حدّ المعدّل (429) — الزرّ يُعطَّل حتى انقضاء المهلة، ولا يُعرض
  /// كخطأ عام: من رأى «حدث خطأ» أعاد المحاولة فوراً فزاد الحدّ اشتعالاً.
  static const String rateLimited = 'throttled';

  /// رقم بلا حساب ولم يُرسَل معه اسم — الشاشة تُظهر حقل الاسم وتعيد الإرسال.
  ///
  /// يُرفَض **قبل** استهلاك الرمز، فالرمز الذي بيد المستخدم ما زال صالحاً ولا
  /// يحتاج رسالة جديدة.
  static const String registrationNeedsName = 'registration_needs_name';

  /// المزوّد لم يحمل الرسالة — عطل عندنا لا خطأ من العميل.
  ///
  /// الفرع موجود لأن السلوك يختلف: لا يوجد رمز أصلاً ليُكتب، فالشاشة تعرض
  /// «إعادة الإرسال» لا حقل رمز ينتظر أرقاماً لم تصل أحداً. الفيز 007 (T603)
  /// جعل هذا 503 لا 409 لنفس السبب.
  static const String smsUndeliverable = 'sms_undeliverable';

  /// طلب رمز جديد والرمز السابق ما زال حيّاً — مع `detail.retry_after` بالثواني.
  static const String otpResendTooSoon = 'otp_resend_too_soon';
}
