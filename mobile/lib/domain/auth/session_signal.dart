import 'dart:async';

/// إشارة «انتهت الجلسة» من طبقة البيانات إلى التوجيه.
///
/// من يكتشف ضياع الجلسة هو اعتراض المصادقة: طلبٌ ردّ عليه الخادم بـ401 ثم فشل
/// تجديد الرمز. ومن يجب أن يتصرّف هو الموجّه، لا الشاشة التي صادف أنها كانت
/// مفتوحة — بلا هذه الإشارة تحتاج **كل** شاشة أن تعرف 401 وأن تعيد التوجيه،
/// وهي نقطة قرار مكرَّرة تسقط أول ما تُنسى في شاشة (المادة ٤-٥).
///
/// تعيش في `domain` لأن الطرفين — `data` التي ترفع الإشارة و`presentation`
/// التي تسمعها — لا يجوز أن يعرف أحدهما الآخر.
final class SessionSignal {
  final StreamController<void> _lost = StreamController<void>.broadcast();

  /// حدث لكل مرة تضيع فيها الجلسة. `broadcast` لأن السامع قد يتأخّر في
  /// الاشتراك، ولأن أكثر من طرف قد يسمع (الموجّه، وتنظيف الكاش لاحقاً).
  Stream<void> get lost => _lost.stream;

  void reportLost() {
    if (!_lost.isClosed) _lost.add(null);
  }

  Future<void> dispose() => _lost.close();
}
