import '../entities/push_notification.dart';

/// الجهاز على أي منصة يعمل — يقرّره الجهاز نفسه، لا شاشة ولا خادم.
enum DevicePlatform { android, ios }

/// جانب **الجهاز** من الإشعارات: الإذن، والرمز، والرسائل.
///
/// عقد نطاقي بلا أي أثر لـFirebase عمداً. مزوّد الدفع تفصيلة نقل مثل dio:
/// لو استُبدل غداً، تُستبدل نسخة واحدة تحت `data/` ولا تتغيّر شاشة ولا usecase.
/// والأهم أنه يجعل مسار «سُجّل ← وصل إشعار ← فُتحت الشاشة» قابلاً للاختبار بلا
/// جهاز ولا شبكة.
abstract interface class PushService {
  /// المنصة التي يعمل عليها هذا الجهاز — تُرسل مع التسجيل.
  DevicePlatform get platform;

  /// يطلب إذن الإشعارات من المستخدم. `false` تعني رفضاً صريحاً أو حجباً.
  Future<bool> requestPermission();

  /// رمز هذا الجهاز عند المزوّد، أو `null` إن تعذّر الحصول عليه.
  Future<String?> currentToken();

  /// المزوّد يدوّر الرمز من تلقاء نفسه (إعادة تثبيت، استرجاع نسخة احتياطية).
  /// كل رمز جديد يُعاد تسجيله وإلا صمت الجهاز بلا أن يعرف أحد.
  Stream<String> tokenRefreshes();

  /// إشعارات تصل والتطبيق مفتوح.
  Stream<PushNotification> foregroundMessages();

  /// المستخدم ضغط إشعاراً والتطبيق في الخلفية.
  Stream<PushNotification> notificationTaps();

  /// الإشعار الذي أقلع منه التطبيق وهو مغلق تماماً، إن وُجد.
  ///
  /// منفصل عن `notificationTaps` لأنه ليس حدثاً في مجرى: التطبيق لم يكن يعمل
  /// ليسمعه، فيُسأل عنه مرة واحدة عند الإقلاع. دمجهما يضيع أكثر الحالات
  /// شيوعاً — إشعار يضغطه المستخدم وتطبيقه مغلق.
  Future<PushNotification?> initialNotification();

  /// يبطل رمز هذا الجهاز عند المزوّد. يُستدعى عند الخروج.
  Future<void> deleteToken();
}
