import 'push_service.dart';

/// جانب **الخادم** من الإشعارات: من يملك هذا الجهاز.
///
/// ⚠️ لا معامل `userId` في أي دالة هنا، وغيابه هو التصميم كله. المالك يأتي من
/// رمز الدخول في ترويسة الطلب، لا من جسمه. في v1 كان معرّف الحساب حقلاً في
/// الجسم، فكان تسجيل جهاز باسم عميل آخر بُعد حقلٍ واحد — وإشعارات هذه القناة
/// تقول على ماذا يزايد الرجل وبكم.
///
/// إضافة معامل مالك هنا مستقبلاً تعيد فتح الثغرة نفسها. يحرسه
/// `test/architecture/device_registration_has_no_owner_field_test.dart`.
abstract interface class DeviceRegistry {
  /// يربط هذا الرمز بصاحب الجلسة الحالية.
  Future<void> register({
    required String token,
    required DevicePlatform platform,
  });

  /// يفكّ ارتباط هذا الرمز بصاحب الجلسة الحالية.
  ///
  /// يُستدعى **قبل** محو الرموز من التخزين الآمن: بعده لا جلسة تُثبت الملكية،
  /// فيردّ الخادم 401 ويبقى الجهاز مسجَّلاً على حساب من خرج.
  Future<void> unregister({required String token});
}
