/// حسابُ الشركة الذي يُحوَّل إليه. T954.
///
/// **قناتان لشحن التأمين**: ميسر بالبطاقة، والحوالةُ البنكيّة. وكان زرُّ
/// الحوالة في التطبيق يردّ «قريباً» بلا رقم حساب، فالعميلُ الذي يريد التحويل
/// لا يجد إلى أين يحوّل.
///
/// **والفاتورةُ حوالةٌ وحدَها** بعد قرار المالك (١٩ سبتمبر ٢٠٢٦): «رصيد
/// التأمين لا يمكن وممنوع السداد منه للفواتير. بعد سداد فاتورة العربية يقدر
/// يسترد التأمين» — وهي المادةُ السادسة: «مبلغ الضمان لا يُحتسب من ثمن
/// المركبة».
///
/// والبياناتُ من الخادم لا مكتوبةٌ هنا: حسابُ الشركة يتغيّر، ومكتوباً في
/// التطبيق يعني إصداراً جديداً على المتجرَين لتغيير رقم.
final class BankAccount {
  const BankAccount({
    required this.configured,
    required this.beneficiary,
    required this.bank,
    required this.iban,
    required this.account,
  });

  /// أضُبط الحسابُ على الخادم؟
  ///
  /// علمٌ صريحٌ لا استنتاجٌ من فراغ الحقول: شاشةٌ تقرأ أربعةَ نصوصٍ فارغة
  /// ترسمها أربعةَ أسطرٍ فارغةٍ وتظنّها بياناتٍ ناقصة.
  final bool configured;

  final String beneficiary;
  final String bank;

  /// رقمُ الآيبان — **وهو ما يُحوَّل إليه فعلاً**.
  final String iban;

  /// رقمُ الحساب، مكمّلٌ تطلبه بعضُ البنوك. قد يكون فارغاً.
  final String account;
}
