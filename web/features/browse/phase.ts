/**
 * التبويب — يُقرأ من العنوان، ويُسأل عنه الخادم. T1030.
 *
 * التبويب في العنوان لا في حالة عميل
 * ==================================
 * `?phase=active` جزءٌ من الرابط، ولذلك: يُشارَك كما هو، ويُرندَر في الخادم
 * فيصل مركَّباً في الـHTML، ويصمد عبر إعادة التحميل وزرّ الرجوع، وتفهرسه
 * محركات البحث بوصفه ثلاث صفحات لا صفحةً تتبدّل. تبويبٌ يعيش في `useState`
 * يفقد الأربعة دفعةً واحدة، ويجعل الشاشة تحتاج جافاسكربت لتقول أيّ شيء.
 *
 * وما لا يُقرَّر هنا
 * ================
 * أيُّ مركبةٍ في أيّ تبويب. هذا الملف يقرأ كلمةً من العنوان ويتحقّق أنها من
 * الثلاث، ثم يمرّرها. من يقرّر أن مزاداً «نشط» هو الخادم — لا مقارنةُ وقتٍ
 * هنا، ولا اشتقاقٌ من `state` (المادة ٤-٥ والقاعدة «حالة المزاد كما قالها
 * الخادم»).
 *
 * والأسماء العربية للتبويبات الثلاثة اسمُ **مرشِّح تعرضه هذه الشاشة**، لا اسمُ
 * حالةٍ يحملها سجل: حالات السجلات تصل من الخادم في `state_label` ولا تُترجَم
 * هنا أبداً. وهي مكتوبة مرة واحدة في هذا الملف لأن كتابتها مرتين هي أن يقول
 * التبويب شيئاً ويقول عنوان الصفحة غيره.
 */

import { PHASES, type Phase } from "@/lib/api";

export { PHASES };
export type { Phase };

/**
 * التبويب حين لا يقول العنوان شيئاً.
 *
 * «نشط» لأن مزاداً واحداً في الأسبوع يعني أن السؤال الأول دائماً «ما المعروض
 * الآن؟»؛ ومن يريد القادم أو المنتهي يطلبه.
 */
export const DEFAULT_PHASE: Phase = "active";

interface Tab {
  id: Phase;
  /** اسم التبويب. */
  label: string;
  /** لماذا هذا التبويب فارغ — جملةٌ تقول السبب، لا شبكةٌ بيضاء. */
  empty: string;
}

export const TABS: readonly Tab[] = [
  { id: "upcoming", label: "قريباً", empty: "لا مزاد قادم الآن." },
  { id: "active", label: "نشط", empty: "لا مزاد جارٍ الآن — تابع تبويب «قريباً»." },
  { id: "ended", label: "منتهي", empty: "لا مزاد منتهٍ بعد." },
];

export function tabOf(phase: Phase): Tab {
  //: `TABS` مبنيّة على `PHASES` نفسها، فالبحث لا يخيب؛ والافتراضي هنا يمنع
  //: `undefined` من التسرّب إلى نوعٍ يعد بغير ذلك.
  return TABS.find((tab) => tab.id === phase) ?? TABS[1]!;
}

/** التبويب المطلوب في العنوان. كلمةٌ لا نعرفها تعود إلى الافتراضي، لا إلى 404. */
export function readPhase(params: URLSearchParams): Phase {
  const asked = params.get("phase");
  return PHASES.find((phase) => phase === asked) ?? DEFAULT_PHASE;
}
