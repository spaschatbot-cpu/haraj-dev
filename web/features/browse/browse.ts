/**
 * الشبكة والعدّادات في طلب واحد — T1030.
 *
 * لماذا طلبٌ واحد، ولماذا هذا ليس تحسيناً اختيارياً
 * ==================================================
 * v1 كان يطلب ستة طلبات ليعرض ثلاثة أرقام: `counts_only=1` مرة لكل نوع، ثم
 * مكرّرةً مرة ثانية بترتيب معاملات مختلف. والعطب ليس في العدد بل في أن كل رقم
 * صار من **لحظة مختلفة**: مزادٌ يبدأ بين الطلب الأول والثالث يُعدّ مرتين أو لا
 * يُعدّ، فيقول التبويب «١٢» ويفتح على أحد عشر، ولا يساوي مجموعُ التبويبات أيّ
 * شيء يمكن مراجعته.
 *
 * والتبويبات تحتاج الأرقام الثلاثة كلها في كل حال — لا فرع في الشاشة يعرض
 * تبويباً بلا عدّاده — فطلبُها مع الصفحة نفسها هو الشكل الصحيح، لا اختصارٌ له.
 *
 * ولا حساب هنا
 * ============
 * العدّادات تصل كما هي وتُعرض كما هي. لا `results.length`، ولا جمعٌ، ولا
 * استنتاجٌ من `total`: `total` هو عدد نتائج **هذا** التبويب بعد الترشيح،
 * والعدّاد هو عدد التبويب — ولو اشتُقّ أحدهما من الآخر لانهار الاثنان أول مرة
 * يُكتب فيها بحث.
 */

import { api, request, type Phase, type PhaseCounts, type Vehicle, type VehiclePage } from "@/lib/api";

export interface Browse {
  vehicles: Vehicle[];
  /** عدد نتائج هذا التبويب بعد الترشيح — للترقيم. */
  total: number;
  /**
   * عدّاد كل تبويب، أو `null` إن لم يقل الخادم.
   *
   * `null` وليس أصفاراً: «٠» جملةٌ تعني «لا شيء هناك»، و«لم يقل الخادم» شيءٌ
   * آخر تماماً. التبويب يُعرض بلا رقم حينها — انظر `PhaseTabs`.
   */
  counts: PhaseCounts | null;
}

export async function browse({
  phase,
  filters,
  limit,
  offset,
}: {
  phase: Phase;
  /** المرشِّحات كما وصلت من العنوان، بعد أن حُصرت في ما يعلنه العقد. */
  filters: Record<string, string>;
  limit: number;
  offset: number;
}): Promise<Browse> {
  //: التبويب مرشِّحٌ بين مرشِّحات على السلك، فيُبنى معها في خريطة واحدة —
  //: وترتيب المعاملات ثابت لأن ردّاً مخزَّناً بمفتاح مختلف لنفس السؤال هو نصف
  //: العطب الذي كان في v1.
  const query: Record<string, string> = { phase, ...filters };

  const page = (await request(() =>
    api.GET("/api/v1/vehicles/", { params: { query: { limit, offset, ...query } } }),
  )) as VehiclePage;

  return {
    vehicles: page.results ?? [],
    total: page.total,
    counts: page.counts ?? null,
  };
}
