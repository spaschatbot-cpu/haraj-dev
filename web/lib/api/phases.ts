/**
 * أسماء الأطوار الثلاثة — مشتقّةً من المخطط المولَّد، لا مكتوبةً بجواره.
 *
 * ما حلّ محلّه هذا الملف
 * ======================
 * كان هنا `awaiting.ts`: طبقةٌ مؤقّتة تعلن `phase` و`counts` و`auction_ends_at`
 * بيدٍ لأن الويب سبق العقد. وكانت تحمل تاريخ انتهائها في اختبارٍ يفشل يوم
 * يعلن المخطط هذه الحقول — وقد فشل، فحُذفت. تلك هي القصة كاملة، وهي السبب في
 * أن هذا الملف موجودٌ أصلاً بدل أن تُستورد الأنواع من `schema.ts` مباشرة.
 *
 * لماذا بقي منه شيء
 * =================
 * `Phase` و`PhaseCounts` يأتيان الآن من المولَّد. لكن **قيم** الأطوار لا
 * تُشتقّ من نوعٍ في زمن التشغيل: التبويبات تحتاج مصفوفةً تمرّ عليها، و
 * TypeScript لا يُبقي من الاتحاد شيئاً بعد الترجمة.
 *
 * فبدل أن تُكتب المصفوفة بيد — وهو ما جعل الويب يسمّي الطور الأول `upcoming`
 * والخادم يسمّيه `soon`، فيردّ التبويب ٤٠٠ — تُشتقّ من **مفاتيح** `PhaseCounts`
 * التي يعلنها المخطط. والنوع أدناه يجعل الترجمة تفشل لو زاد المخطط طوراً
 * رابعاً أو أعاد تسمية واحد، فلا يبقى الاسم قراراً يُتَّخذ هنا.
 *
 * ويحرس `ops/checks/web_phase_names_match_the_server.mjs` الأمرَ نفسه من
 * الخارج، لأن الحارس الذي يعيش داخل ما يحرسه يسقط معه.
 */

import type { components } from "./schema";

/** عدّاد لكل تبويب، محسوبٌ في الخادم في اللحظة التي رُسمت فيها الصفحة. */
export type PhaseCounts = components["schemas"]["PhaseCounts"];

/** الطور كما يسمّيه الخادم. اسمٌ على السلك، لا اختيار عرض. */
export type Phase = keyof PhaseCounts;

/**
 * الأطوار الثلاثة بترتيب عرضها: قريباً ثم نشط ثم منتهي — رحلةُ المزاد نفسها.
 *
 * `satisfies` هي الحارس: مصفوفةٌ ينقصها طورٌ يعلنه المخطط، أو فيها اسمٌ لا
 * يعلنه، تُفشل الترجمة. والترتيب يبقى قراراً هنا لأن المخطط لا يملك ترتيباً.
 */
export const PHASES = ["soon", "active", "ended"] as const satisfies readonly Phase[];

/**
 * ولا طورَ في المخطط خارج هذه المصفوفة.
 *
 * `satisfies` أعلاه يمنع الاسم الخاطئ ولا يمنع الاسم **الناقص**: مصفوفةٌ فيها
 * طوران يرضيه تماماً. هذا النوع يُفشل الترجمة حينها — وطورٌ رابع يُضاف إلى
 * العقد ولا يُعرَض تبويبٌ له عطلٌ صامت بالضبط كالاسم الخاطئ.
 */
type EveryPhaseIsListed = Exclude<Phase, (typeof PHASES)[number]> extends never
  ? true
  : ["ينقص طورٌ من PHASES:", Exclude<Phase, (typeof PHASES)[number]>];

const _everyPhaseIsListed: EveryPhaseIsListed = true;
void _everyPhaseIsListed;
