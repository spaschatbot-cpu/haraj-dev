/**
 * حقول عقد التبويبات — طبقة مؤقّتة تُحذف يوم يحملها المخطط. T1030.
 *
 * ما هذا الملف، ولماذا هو موجود على مضض
 * ======================================
 * كل نوع في هذا الويب مولَّد من `backend/openapi/schema.yaml` عبر
 * `lib/api/schema.ts`، ولا يُكتب نوعٌ بيد (T1002 / J2). هذا الملف **استثناء
 * معلَن**: تبويبات الحالة تحتاج ثلاثة أشياء لم تصل بعدُ إلى المخطط —
 *
 *   · معامل `phase` على `GET /api/v1/vehicles/`؛
 *   · حقل `counts` بجوار `results` و`total` في الصفحة؛
 *   · `auction_id` و`auction_ends_at` على كرت المركبة.
 *
 * فُصلت هنا في ملف واحد بدل أن تُبعثر في المكوّنات، لسببين: أن يكون
 * لـ«ما ينتظره الويب من العقد» عنوانٌ واحد يُقرأ، وأن يكون حذفها لاحقاً
 * تعديلاً في ملف واحد لا مطاردةً في شجرة.
 *
 * **الحقول كلها اختيارية، وهذا ليس تهاوناً.** خادمٌ لم يُحدَّث بعد يرد صفحةً
 * بلا `counts`، والصواب حينها أن يظهر التبويب **بلا رقم** لا أن يظهر بصفر:
 * «صفر» جملةٌ تعني «لا مزاد قادم»، والحقيقة أن الخادم لم يقل شيئاً. ورقمٌ
 * مخترَع في الواجهة هو بالضبط ما تمنعه القاعدة «العدّادات من الخادم».
 *
 * ومتى يُحذف؟
 * ===========
 * يوم يعلن المخطط هذه الحقول. و`lib/__tests__/phase-tabs.test.ts` يفشل يومها
 * صراحةً ويقول «احذف الطبقة» — لأن طبقةً مؤقّتة بلا تاريخ انتهاء تصير نوعاً
 * مكتوباً بيد يتعايش مع المولَّد، ثم يختلفان.
 */

import type { components } from "./schema";

/** الحالات الثلاث كما يسمّيها الخادم. التسمية عقد، لا اختيار عرض. */
export const PHASES = ["soon", "active", "ended"] as const;

export type Phase = (typeof PHASES)[number];

/** عدّاد لكل تبويب، محسوبٌ في الخادم في اللحظة نفسها التي رُسمت فيها الصفحة. */
export type PhaseCounts = Record<Phase, number>;

/**
 * كرت المركبة، وقد أضاف إليه العقد مزادَه ولحظةَ انتهائه.
 *
 * `auction_ends_at` لحظة UTC، وهي لحظة انتهاء **المزاد** لا المركبة — العدّاد
 * على الكرت يحتاجها، وهي السبب الوحيد لوجودها هنا. v1 كان يرسلها مع كل مركبة
 * أيضاً، وهو الشيء الوحيد الذي أصابه في ذلك الرد.
 */
export type Vehicle = components["schemas"]["VehicleCard"] & {
  auction_id?: number;
  auction_ends_at?: string | null;
};

/**
 * صفحة المركبات، والعدّادات الثلاثة معها في الرد نفسه.
 *
 * الثلاثة معاً في طلب واحد ليست تحسيناً للأداء. التبويبات تحتاج الأرقام
 * الثلاثة في كل حال، وطلبُها مفرّقةً يجعل كل رقم من لحظة مختلفة — فيصير مجموع
 * التبويبات لا يساوي شيئاً، ويصير التبويب يقول «١٢» ويفتح على أحد عشر.
 */
export type VehiclePage = Omit<components["schemas"]["VehiclePage"], "results"> & {
  results?: Vehicle[];
  counts?: PhaseCounts;
};
