"""مطابقةُ النصّ العربيّ في البحث — دالّةٌ واحدةٌ لكلّ شاشات اللوحة. T897.

## العطل الذي فتح هذا الملفّ

كان التطبيعُ يعيش في `console/vehicle_filters.py` وحده، ويُستعمل في **موضعٍ
واحد**: فلاترُ أعمدةِ جدولِ المركبات، ومطابقتُها في بايثون على صفوفٍ مُحمَّلة.
وبقيّةُ شاشات اللوحة — والمزايدات أهمُّها — تقارن `icontains` حرفياً. وكان
مكتوباً في رأس `console/bids.py` وفي `_searched` أن البحثَ «يطبّع العربية»
وأن ذلك تفوّقٌ على v1، **والاستيرادُ نفسُه لم يكن يُستدعى في سطرٍ واحد**
(أمسكه `ruff` بـ`F401`). أي أن الشرحَ كان يَعِد بسلوكٍ غيرِ موجود.

## ولماذا يهمّ الموظّفَ لا المبرمجَ

من يبحث «احمد» لا يجد «أحمد»، ومن يكتب «١٢٦٥» لا يجد «1265»، ومن ينسخ لوحةً
من ورقةٍ فيكتب «دطق1265» لا يجد «د ط ق 1265» — وهي مكتوبةٌ هكذا بمسافاتٍ في
قاعدتنا المُرحَّلة فعلاً. **والموظّفُ لا يقرأ «البحثُ لا يُطبّع» بل «العميلُ
غيرُ موجود»**، فيُنشئ حساباً ثانياً لمن له حساب. وذاك عطلُ v1 المعروف: حساباتٌ
مكرَّرةٌ لشخصٍ واحد، ومالٌ موزَّعٌ على اثنين.

## القرار: تُطبَّع الحافّتان، والعمودُ يُطابَق بتعبيرٍ نمطيّ

لا تُوجد في القاعدة دالّةٌ تطبّق `fold` على العمود، وتطبيعُ المُدخَل وحده
**لا يجد شيئاً أبداً**: «الماركه» ليست جزءاً من «الماركة». فأمامنا ثلاثةُ
طرق، واختير الثالث:

1. **مطابقةٌ في بايثون** (ما يفعله `vehicle_filters._apply_text` اليوم): تقرأ
   صفوفَ الجدول كلَّها إلى الذاكرة. مقبولةٌ على مزادٍ من مئاتِ الصفوف، ومستحيلةٌ
   على **١٦٣٬٢٨٣ مزايدة**.
2. **عمودُ بحثٍ مُطبَّعٌ مُخزَّن** بهجرةٍ ومُشغِّلٍ يحدّثه: أسرعُ ما يكون مع
   فهرس `gin_trgm_ops`، لكنّه بيانٌ مكرَّرٌ يتفارق عن أصله عند أوّل كتابةٍ خام
   (استيراد، هجرة، `update()`). قرارٌ أثقلُ من أن يُتّخذ بلا قياسٍ يبرّره،
   **فعُرض ولم يُنفَّذ** — والقياسُ أدناه يقول إنه غيرُ لازمٍ اليوم. ويبقى
   معروضاً ليومٍ تتجاوز فيه المزايداتُ المليون، أو يُطلب فيه بحثٌ ضبابيّ.
3. **توسيعُ المُدخَل المطبَّع إلى تعبيرٍ نمطيّ** يقبل كلَّ صور الحرف في العمود
   الخام: «ا» تصير `[اأإآ]`، و«ه» تصير `[هة]`، و«1» تصير `[1١۱]`، ويُسمح بين
   كلّ حرفين بتشكيلٍ وتطويلٍ ومسافةٍ وشرطة. فالمطابقةُ تبقى في القاعدة وقبل
   الترقيم، ولا يُقرأ صفٌّ إلى الذاكرة.

**وحيث الجدولُ كبير، يُحلّ البحثُ على الجدول الصغير ثم يُربط بالمفتاح
المفهرس**: `Bid` فيه ١٦٣٬٢٨٣ صفّاً، فتطبيقُ التعبير على ستّة أعمدةٍ عبر
وصلتين كلفتُه ١٤٣٢ms (مقيس). وحلُّه على `Vehicle` (١٢٬٩٨١) و`User` (٤٤٬٠٣٦)
ثم `vehicle__in` / `bidder__in` كلفتُه **٤١٤ms** — أي **أقلُّ من الـ٧٩٨ms**
التي كان يكلّفها `icontains` قبل التطبيع أصلاً. انظر `console/bids._searched`.

**وثمنُ الفهرس صفرٌ هنا، وهذا هو مفتاحُ القرار:** `icontains` يُترجَم إلى
`LIKE '%…%'`، والنجمةُ البادئة تُسقط فهرسَ B-tree أصلاً — و`auctions_vehicle`
ليس عليه فهرسُ trigram واحد (فُحص: `vin_…_like` و`claim_number_…_like` كلاهما
`varchar_pattern_ops`، يخدم البادئةَ لا الاحتواء). فالمسحُ الكامل كان يجري
قبل هذا التغيير وبعده، والفرقُ كلفةُ `~*` مقابل `LIKE` على الصفّ الواحد لا
خطّةُ استعلامٍ مختلفة.

## وماذا يفعل v1 (قُرئ، ولم يُنسخ)

بحثُ v1 كلُّه `LIKE '%<ما كُتب حرفياً>%'`. **ولا توجد في مستودعه دالّةٌ واحدة
تحوّل أ/إ/آ إلى ا، ولا ة إلى ه، ولا ى إلى ي** — لا في PHP ولا في JS. الموجودُ
عنده ثلاثةُ مواضعَ تطوي **الأرقام** وحدها: `foldArabicDigits` في بحث المزادات،
و`foldDigits` داخل `initColumnFilters` (وهو وحده يحذف التشكيل والمسافات، في
المتصفّح لا في القاعدة)، و`normalizeDigits` عند **الكتابة** لحقول الهوية. ولا
عمودَ بحثٍ مطبَّعاً مخزَّناً ولا فهرسَ `FULLTEXT` ولا `COLLATE` يُعادل الهمزات.
فما نُقل عنه هو **الشرط** — أرقامٌ عربية-هندية تُطوى، ولوحةٌ تُطابَق بلا
مسافات (`REPLACE(Plate_number,' ','')`) — لا البنية، وما فوقه من همزاتٍ وتاءٍ
مربوطةٍ وتشكيلٍ زيادةٌ مقصودة.

## حدودٌ معلومةٌ يُقال بها

* `NFKC` يُطبَّق على المُدخَل ولا يُطبَّق على العمود — لا سبيل إليه في SQL بلا
  دالّةٍ مخزَّنة. فصورةُ حرفٍ تقديميّة (`ﺍ`) مكتوبةٌ في العمود لا تُطابَق.
  وقُيس على `haraj2_t307`: صفرُ صفٍّ في `make`/`model`/`plate_number` فيه محرفٌ
  من `U+FB50..U+FEFF`. فالحدُّ قائمٌ ولا أثرَ له اليوم.
* والأثرُ مقيسٌ لا موصوف. على `haraj2_t307` (١٦٣٬٢٨٣ مزايدة · ١٢٬٩٨١ مركبة):
  «شاحنه» كانت تعطي ١٠٧١ مزايدةً وصارت ١٢٧٩ (و«شاحنة» ٢٠٨ ← ١٢٧٩، فاجتمع
  الإملاءان على رقمٍ واحد)، و«مرسيدس رأس» ٠ ← ٧٥٥، و«لكزس اي اس» ٧٥٢ ← ٢٠٢٠،
  و«١٢٦٥» ٠ ← ٢٥، و«دطق1265» على المركبات ٠ ← ١.
* التطبيعُ لا يمسّ اختلافَ **الإملاء**: «هونداي» و«هيونداي» كلمتان مختلفتان
  (٢٢١٠ و٥٢ صفّاً في القاعدة)، ولا يجمعهما حذفُ همزةٍ ولا تشكيل. ذلك بحثٌ
  ضبابيّ (trigram) لا تطبيع، وهو بندٌ آخر.
* الجوّالُ يُطابَق كما هو مخزَّنٌ (`9665…`)؛ **من يكتب `05…` لا يجد** — وهي
  ثغرةٌ قائمةٌ في v1 نفسِه خارج ثلاثة مواضع (`phoneLookupVariants` في محفظة
  العميل، وآخرُ تسعةِ أرقامٍ في `UserController`). تحويلُ صيغِ الجوّال مسألةٌ
  مستقلّةٌ عن تطبيع الحروف، **ولم تُعالَج هنا** ولا يُدَّعى أنها عولجت.
"""

from __future__ import annotations

import re
import unicodedata

from django.db.models import Q

__all__ = ["MAX_INPUT", "fold", "matches", "pattern", "search_q"]

_ARABIC_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩", "0123456789")
_PERSIAN_DIGITS = str.maketrans("۰۱۲۳۴۵۶۷۸۹", "0123456789")

#: ما يُحذف من الطرفين: التشكيلُ والتطويل.
_MARKS = "ً-ْـ"

#: ما يُحذف من المُدخَل ويُسمح به بين حروف العمود — فـ«دطق1265» تجد
#: «د ط ق 1265»، وهي مكتوبةٌ بمسافاتٍ في ٩٩٪ من لوحات القاعدة المُرحَّلة.
_GAPS = r"\s\-_./"


def fold(text) -> str:
    """طيُّ النصّ إلى صورته المطابِقة — تُستعمل للمُدخَل ولقيمة العمود معاً.

    كما في فلاتر v1 (`initColumnFilters`): الأرقامُ العربية-الهندية ٠-٩
    والفارسية ۰-۹ إلى ASCII — فلوحةُ المفاتيح العربية تُخرج «٣١٠» حيث الخليّة
    «310». وفوق v1: أ إ آ←ا · ى←ي · ة←ه، وحذفُ التشكيل والتطويل — فـ«الماركه»
    تجد «الماركة». ثم `lower` وحذفُ المسافات و`- _ . /`.

    وكلُّ سطرٍ هنا له نظيرُه في `pattern` أدناه: من يزيد طيّاً هنا ولا يزيده
    هناك يصنع بحثاً يجد نصفَ ما يَعِد به.
    """
    chars = str(text or "")
    chars = chars.translate(_ARABIC_DIGITS).translate(_PERSIAN_DIGITS)
    chars = re.sub("[أإآ]", "ا", chars)
    chars = chars.replace("ى", "ي").replace("ة", "ه")
    chars = chars.replace("ـ", "")
    chars = re.sub("[ً-ْ]", "", chars)
    chars = unicodedata.normalize("NFKC", chars)
    return re.sub(rf"[{_GAPS}]", "", chars.lower())


#: عكسُ `fold`: الحرفُ المطويّ ← صفُّ ما يقبله في العمود الخام. لولا هذا
#: الجدولُ لكان تطبيعُ المُدخَل وحده يضمن ألّا يُوجد شيء.
_CLASSES = {
    "ا": "[اأإآ]",
    "ي": "[يى]",
    "ه": "[هة]",
    "0": "[0٠۰]",
    "1": "[1١۱]",
    "2": "[2٢۲]",
    "3": "[3٣۳]",
    "4": "[4٤۴]",
    "5": "[5٥۵]",
    "6": "[6٦۶]",
    "7": "[7٧۷]",
    "8": "[8٨۸]",
    "9": "[9٩۹]",
}

#: ما يُسمح بوجوده بين كلّ حرفين في العمود — لأن `fold` حذفه من المُدخَل.
_BRIDGE = rf"[{_GAPS}{_MARKS}]*"

#: محارفُ التعبير النمطيّ التي يجب أن تبقى حرفاً عادياً. (`. / - _` والمسافةُ
#: حذفها `fold` أصلاً فلا تصل إلى هنا.)
_META = set(r"\^$.[]|()*+?{}")

#: سقفُ طول المُدخَل بعد الطيّ. كلُّ حرفٍ يصير صفَّ محارفَ وجسراً
#: (`[اأإآ][\s\-_./ً-ْـ]*`)، فطولُ التعبير يتضاعف نحو عشر مرّات — والكلفةُ على
#: القاعدة تنمو مع الطول لا مع عدد الصفوف.
#:
#: **وقِيس على `haraj2_t307` (١٢٬٩٨٨ مركبة) في ١٤ سبتمبر ٢٠٢٦:** `?q=` بـ٩٠٠
#: حرفٍ عربيّ كلفت ١١٠٤ms، وبـ٣٢٠٠ حرفاً ٤٠٦٢ms، وبـ٦٤٠٠ حرفاً ٨٧٦٩ms،
#: وبعشرين ألفاً رفع بوستجرس `DataError: regular expression is too complex`
#: — أي **صفحةَ خطأٍ ٥٠٠** لا نتيجةً فارغة. وكلُّ ذلك بصلاحية عرضٍ وحدها.
#:
#: و١٢٨ محرفاً سقفٌ سخيّ لما يُبحَث به فعلاً: الشاصي ١٧، واللوحة ١٦، وأطولُ
#: اسمِ عميلٍ في القاعدة دون ذلك. وما جاوزه يُقصّ لا يُرفَض — مُدخَلٌ بهذا
#: الطول لا يطابق صفّاً أصلاً، فقصُّه يغيّر «صفرٌ في ثمانِ ثوان» إلى «صفرٌ في
#: جزءٍ من الثانية» ولا يغيّر جواباً رآه موظّف.
MAX_INPUT = 128


def pattern(text) -> str:
    """المُدخَلُ مطويّاً ثم موسَّعاً إلى تعبيرٍ نمطيّ يُطابق العمودَ الخام.

    يُعاد `""` لمُدخَلٍ فارغٍ أو لا يبقى منه شيءٌ بعد الطيّ (مسافاتٌ وشرطات)،
    ليقرأه المُنادي «لا بحثَ هنا» فلا يرشّح بتعبيرٍ يُطابق كلَّ صفّ.
    """
    folded = fold(text)[:MAX_INPUT]
    if not folded:
        return ""
    parts = []
    for char in folded:
        if char in _CLASSES:
            parts.append(_CLASSES[char])
        elif char in _META:
            parts.append("\\" + char)
        else:
            parts.append(char)
    return _BRIDGE.join(parts)


def search_q(text, *fields: str) -> Q:
    """`Q` تُطابق النصَّ في أيٍّ من الحقول (OR) — بديلُ سلسلةِ `icontains`.

    الحقولُ بصيغة ORM كاملةً (`vehicle__make`, `bidder__full_name`). ويُعاد
    `Q()` فارغةً لمُدخَلٍ لا يبقى منه شيء، وهي محايدةٌ في `filter` فلا تحجب
    صفّاً — وذلك المطلوب: خانةُ بحثٍ فارغةٌ تعني «الكلّ» لا «لا شيء».
    """
    regex = pattern(text)
    if not regex or not fields:
        return Q()
    clause = Q()
    for field in fields:
        clause |= Q(**{f"{field}__iregex": regex})
    return clause


def matches(value, text) -> bool:
    """مطابقةٌ في بايثون بالعقد نفسِه — لِما لا يأتي من عمودٍ في القاعدة.

    تُستعمل حيث القيمةُ محسوبةٌ لا مخزَّنة (تسميةُ لونٍ من `choices` مثلاً)،
    فلا يصحّ فيها `iregex`. والطيُّ على الطرفين هنا يكافئ التعبيرَ النمطيّ
    هناك — كلاهما `fold` على الحافّتين.
    """
    needle = fold(text)
    return bool(needle) and needle in fold(value)
