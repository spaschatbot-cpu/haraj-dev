"""ترجمةُ نصّ v1 الحرّ إلى تعداداتنا — لوناً وحالةً فنّيّة.

v1 يكتب اللونَ والحالةَ **نصّاً حرّاً بالعربية**: خمسةٌ وسبعون لوناً مختلفاً في
ثلاثةَ عشرَ ألفَ صفّ، فيها «رصاصي فاتح» و«ابيض / اسود» و«حادث». وعندنا تعدادان
مغلقان (:class:`~apps.auctions.models.VehicleColour` و`VehicleCondition`).

**ولماذا جدولٌ لا قصٌّ آليّ.** المقابلةُ ليست ترجمةَ كلمات: «رصاصي» رماديٌّ
وليس رصاصاً، و«تشليح» ليست كلمةً في أيّ قاموسٍ تقابل `salvage`، و«ابيض / اسود»
لونان لا لون. فالجدولُ مكتوبٌ بيدٍ ومقيسٌ على القيم الفعليّة.

**و«غيرُ مدرج» ليست «غيرَ معروفة».**
``other`` تعني: v1 قال لوناً نعرفه ولا مكانَ له في قائمتنا (برتقاليّ، ثنائيّ
اللون). و``unknown`` تعني: **لم يُسجَّل شيء**. وخلطُهما يجعل سؤالاً مشروعاً —
«كم سيّارةً لا نعرف لونَها؟» — بلا جواب: الرقمُ يخلط ما لم يُكتب بما لا يسعه
تعدادُنا، والأوّلُ نقصُ بياناتٍ يُلاحَق والثاني قرارُ تصميمٍ منّا.

**والمطابقةُ بعد الطيّ** (:func:`apps.core.arabic.fold`): v1 يكتب «أبيض»
و«ابيض»، و«رماديّ» بالشدّة وبدونها، وبمسافةٍ زائدةٍ في آخره. فالطيُّ يوحّد
الهمزاتِ والتشكيلَ والمسافات، ومفاتيحُ الجدول مطويّةٌ مثلها.

وما لم يُطابِق يُعدّ ويُقال — في `backfill_v1_fields` سطرٌ بعدد ما لم يُترجَم
وأمثلةٌ منه. **قيمةٌ جديدةٌ تظهر في لقطةٍ قادمة تُرى، ولا تُبتلَع في ``other``
صامتة.**
"""

from __future__ import annotations

from apps.core.arabic import fold

__all__ = ["colour_of", "condition_of", "COLOURS", "CONDITIONS"]


#: لونُ v1 ⇦ قيمةُ `VehicleColour`. مقيسٌ على لقطة ٢٠٢٦-٠٩-٠٥: الاثنتان
#: والعشرون الأولى تغطّي ١٢٬٩٠٠ من ١٣٬٠٧٩ صفّاً (٩٨٫٦٪).
_COLOUR_WORDS: dict[str, str] = {
    "ابيض": "white",
    "اسود": "black",
    "فضي": "silver",
    # «رصاصي» رماديُّ المدافع، ودرجاتُه الثلاث لونٌ واحدٌ عندنا: تعدادُنا لا
    # يحمل «فاتح/غامق» إلا للأزرق، وإضافةُ درجتين لكلّ لونٍ تُضاعف القائمةَ
    # لتخدم ٢٩٩ صفّاً.
    "رمادي": "grey",
    "رصاصي": "grey",
    "رصاصي فاتح": "grey",
    "رصاصي غامق": "grey",
    "ازرق": "blue",
    "ازرق فاتح": "blue",
    "ازرق غامق": "dark_blue",
    "احمر": "red",
    "احمر غامق": "red",
    "اخضر": "green",
    "اخضر فاتح": "green",
    "بني": "brown",
    "بني غامق": "brown",
    "بيج": "beige",
    "ذهبي": "gold",
    "اصفر": "yellow",
    # **ثنائيُّ اللون ليس لوناً في تعدادنا.** «ابيض / اسود» على السيّارة سقفٌ
    # بلونٍ وبدنٌ بآخر، واختيارُ أحدهما يكذب على من يبحث بالثاني.
    "ابيض / اسود": "other",
    "فضي / اسود": "other",
    # برتقاليٌّ لونٌ نعرفه ولا مكانَ له في القائمة — `other` لا `unknown`.
    "برتقالي": "other",
}

#: الحالةُ الفنّيّة. و«حادث» ١٢٬٣٩٨ من ١٣٬٠٧٩ — فهذه شركةُ تأميناتٍ تبيع
#: مركباتِ الحوادث، لا معرضَ سيّاراتٍ مستعملة.
_CONDITION_WORDS: dict[str, str] = {
    "حادث": "accident",
    "غرقان": "flood",
    "غريق": "flood",
    "حريق": "fire",
    "محروق": "fire",
    "تشليح": "salvage",
    "سليم": "running",
    "يعمل": "running",
    "لا يعمل": "not_running",
}


def _table(words: dict[str, str]) -> dict[str, str]:
    """مفاتيحُ مطويّةٌ مرّةً عند الاستيراد لا مرّةً لكل صفّ."""
    return {fold(key): value for key, value in words.items()}


COLOURS = _table(_COLOUR_WORDS)
CONDITIONS = _table(_CONDITION_WORDS)


#: صفاتُ الدرجة. تُحذف عند الفشل وتُعاد المحاولة: «ذهبي فاتح» و«اخضر غامق»
#: و«بني فاتح» ألوانٌ نعرفها بدرجةٍ لا يحملها تعدادُنا — فحذفُ الصفة يُرجعها
#: إلى أصلها بدل أن تسقط في `other`. وقاعدةٌ واحدةٌ أصدقُ من ثلاثين صفّاً في
#: الجدول: كلُّ لونٍ يقبل الدرجتين، وعدُّها يدوياً يفوت ما لم يظهر بعد.
#:
#: **والأزرقُ مستثنىً** لأنه الوحيدُ الذي تحمل قائمتُنا درجتَه (`dark_blue`)،
#: فهو مكتوبٌ صراحةً في الجدول أعلاه ويُطابَق قبل أن يصل هنا.
_SHADES = ("فاتح", "غامق", "غامج", "فاتحه", "غامقه")
_FOLDED_SHADES = tuple(fold(s) for s in _SHADES)


def colour_of(raw) -> str:
    """لونُ المركبة من نصّ v1. الفراغُ ``unknown``، والمجهولُ ``other``."""
    text = fold(str(raw or "").strip())
    if not text:
        return "unknown"
    if text in COLOURS:
        return COLOURS[text]

    # لونٌ بدرجة: تُقطع الدرجةُ من آخره ويُعاد السؤال.
    #
    # **بالقطع لا بالتقسيم**: `fold` تحذف المسافات (قِيس: «ذهبي فاتح» ⇦
    # `ذهبيفاتح`)، فلا كلماتٍ تُقسَّم بعدها. وهي تحذفها عمداً — بها يجد من
    # كتب «دطق1265» لوحةً مخزَّنةً «د ط ق 1265».
    #
    # وما بقي بعد القطع يجب أن يكون لوناً بذاته: «ابيض / اسود» تصير
    # `ابيضاسود` ولا لاحقةَ فيها، فتبقى `other` — وهي لونان بحقّ.
    for shade in _FOLDED_SHADES:
        if text.endswith(shade) and len(text) > len(shade):
            return COLOURS.get(text[: -len(shade)], "other")
    return "other"


def condition_of(raw) -> str:
    """الحالةُ الفنّيّة من نصّ v1.

    و`...` و`…` في العمود ليستا حالةً — كتبها موظّفٌ ليملأ الخانة. تُقرأ
    ``unknown`` كالفراغ تماماً، لأنها هي.
    """
    text = fold(str(raw or "").strip()).strip(".…")
    if not text:
        return "unknown"
    return CONDITIONS.get(text, "unknown")
