"""أيُعرَض هذا الحقلُ لهذا الفاعل؟ — سؤالٌ واحد، وجوابٌ في ملفٍّ واحد. T901.

الشاشةُ تُفتح بقدرةٍ واحدة، **والحقولُ التي فيها ليست كلُّها من صنفٍ واحد**.
«كتالوج السيارات» و«ما بعد البيع» كلتاهما خلف `auctions.view`، وفيهما مبلغُ
فاتورةٍ ومسدَّدُها وباقيها، واسمُ المشتري وجوّالُه — بينما **مركزُ الفواتير**
نفسُه خلف `invoices.view` (`navigation.py`)، و**إدارةُ المستخدمين** خلف
`users.view`. أي أن الصنفَ الواحد من البيانات له قدرتان: قدرةٌ حيث يُقصَد،
وقدرةٌ أخرى حيث يظهر عَرَضاً.

وليست نظريّة: `ConsoleRole` جدولٌ يُنشئ فيه المالكُ دوراً بأيّ حزمةِ قدرات،
فدورٌ اسمُه «موظّف ساحة» بـ`console.access + auctions.view` — وهي الحزمةُ
الطبيعيّةُ لمن يتابع المركبات — كان يقرأ مبالغَ فواتيرِ العملاء وجوّالاتِهم.

**حكمُ المالك (١٤ سبتمبر ٢٠٢٦): تُحجب الأعمدةُ الحسّاسة، والشاشةُ تبقى
مفتوحة.** من يملك `auctions.view` له حقٌّ في رؤية المزادات ومركباتها؛ الذي لا
حقَّ له فيه هو **المبلغُ والجوّال**.

لماذا `invoices.view` للمال لا `money.view`
===========================================
`money.view` اسمُها في التعداد «عرض دفتر التأمينات والحركات» وشاشاتُها كلُّها
في قسم «المحفظة» — رصيدُ العميل وحركاتُه وتأميناتُه. والمعروضُ هنا **فاتورةُ
فوزٍ ومسدَّدُها**، وهي بعينها ما يعرضه `console:invoices` («مركز الفواتير —
فواتير الفوز وما سُدّد منها وما تأخّر») خلف `invoices.view`. فالقدرةُ الصحيحة
هي التي تحرس الشاشةَ التي يُقصَد فيها هذا الرقمُ أصلاً، لا قدرةٌ أوسعُ منها
تحرس دفتراً آخر. وكلُّ أدوار الشيفرة الأربعة تحمل `INVOICES_VIEW` فعلاً
(`permissions.py`)، فالحجبُ لا يغيّر شيئاً على موظّفٍ قائمٍ اليوم — إنّما
يُغلق البابَ على دورٍ مخصَّصٍ يُنشأ غداً.

وما لا يُحجَب — وسببُه
=====================
**رقمُ الفاتورة وحالتُها يبقيان** بـ`auctions.view`. السؤالُ «أفُوتِرت هذه
المركبة؟» سؤالُ تشغيلٍ لا سؤالُ مال، وv1 نفسُه يضع **رقمَ الفاتورة وحده** في
مصدر الصفحة ثم يجلب بقيّتَها عند الضغط (`Views/Admin/vehicles/catalog.php:711`
⇐ `/admin_v2/after-sales/invoice`). فالمحجوبُ هو ما سمّاه المالك: المبلغُ
والجوّال.

والحجبُ في الخادم لا في CSS
===========================
الحقلُ الذي لا يُعرَض **لا يصل القالبَ أصلاً**: :func:`prepare` تمحوه من صفوف
الصفحة قبل العرض، والقالبُ يسأل :class:`Shown` قبل أن يكتب `data-*`. وذلك هو
العطلُ بعينه الذي أُصلح: `data-phone="966…"` و`data-amount` كانتا في **مصدر
الصفحة** لكلّ صفٍّ مفوتَر — تدخل ذاكرةَ المتصفّح المؤقّتة، وتظهر في «عرض
المصدر»، وتُقرأ في مشاركةِ شاشة — فحجبٌ بصريٌّ فوقها ليس حجباً.
"""

from __future__ import annotations

from dataclasses import dataclass

from apps.core.permissions import Capability, can

#: قدرةُ المبالغ: مبلغُ الفاتورة والمسدَّدُ والباقي ومجاميعُها.
MONEY = Capability.INVOICES_VIEW

#: قدرةُ بيانات العميل: اسمُ المشتري وجوّالُه.
CUSTOMER = Capability.USERS_VIEW


@dataclass(frozen=True)
class Shown:
    """ما يحقُّ لهذا الفاعل أن يراه من الصفّ — لا أكثر."""

    money: bool
    customer: bool


def shown_to(user) -> Shown:
    """اسأل البوّابةَ مرّةً واحدةً للطلب كلِّه.

    مرّةً لا مرّةً لكلّ صفّ: :func:`~apps.core.permissions.can` تستعلم عن
    `StaffGrant` في كلّ نداء، وخمسون صفّاً × حقلين = مئةُ رحلةٍ إلى القاعدة
    لسؤالٍ جوابُه واحدٌ في الطلب كلِّه.
    """
    return Shown(money=can(user, MONEY), customer=can(user, CUSTOMER))


def person_on(rows, seen: Shown, *, field: str = "awarded_to") -> None:
    """اسمُ صاحب الصفّ وجوّالُه في `buyer_name`/`buyer_phone` — أو فارغَين.

    و`field` لأن الشخصَ ليس اسمُه واحداً في كل جدول: المركبةُ لها `awarded_to`
    والمزايدةُ لها `bidder`، وهما الشخصُ نفسُه في القاعدة (`Customer`) وسؤالُه
    واحد. فدالّةٌ واحدةٌ باسم حقلٍ متغيّر، لا دالّةٌ لكلّ جدول — لأن الثانيةَ
    تُصلَح في واحدةٍ وتُنسى في أختها، وهو العطلُ الذي جاءت منه هذه المهمّة.
    """
    for row in rows:
        who = getattr(row, field, None) if seen.customer else None
        row.buyer_name = who.full_name if who else ""
        row.buyer_phone = who.phone if who else ""


def prepare(rows, seen: Shown) -> None:
    """اكتبْ على كلّ صفٍّ ما يُعرَض منه فعلاً — والمحجوبُ يُمحى هنا.

    واسمُ المشتري وجوّالُه يخرجان في `buyer_name` و`buyer_phone` لا يُقرآن من
    `row.awarded_to` في القالب: حقلٌ يُقرأ من علاقةٍ في القالب لا يمرّ من هنا،
    فيبقى بابٌ مفتوحٌ في شاشةٍ أُغلق في أختها — وهو بعينه ما نُصلحه.

    وسعرُ الرسو يخرج في `award_price` — **ولا يُكتب على `awarded_price`**
    ===================================================================
    لأن `awarded_price` عمودٌ حقيقيٌّ في `Vehicle`، خلافاً لـ`invoice_amount`
    وأخواتها (تعليقاتُ استعلامٍ لا أعمدة). فمحوُه على الصفّ يعني أن أيَّ
    `save()` يقع على ذلك الصفّ بعد العرض يكتب `NULL` فوق سعرِ رسوٍّ حقيقيّ —
    حجبُ عرضٍ يصير إتلافَ بيان. والحقلُ الجديد يُقرأ في القالب ولا يُكتب أبداً.

    وهو مالٌ كفاتورته: الكارتُ في أرشيف المزادات يعرض «مبلغ المزايدة» و«إجمالي
    الفاتورة» متجاورَين، والفرقُ بينهما الرسمُ والضريبةُ وحدَهما (قيدُ القاعدة
    `net + fee + tax == amount`). فحجبُ الثاني وإظهارُ الأوّل ليس حجباً.
    """
    person_on(rows, seen)
    for row in rows:
        if not seen.money:
            row.invoice_amount = None
            row.invoice_paid = None
            row.invoice_residual = None
        row.award_price = getattr(row, "awarded_price", None) if seen.money else None


def columns_for(columns, seen: Shown):
    """أعمدةُ تصديرٍ منقوصةً ما لا يحقّ رؤيتُه — **الملفُّ يرث حارسَ الشاشة**.

    عمودٌ يخرج في ملفٍّ ولا يظهر على شاشةٍ هو بعينه بابُ التسريب الذي أُغلق
    فوق: من يفتح الشاشة يضغط «تصدير» فيأخذ في ملفٍّ واحدٍ ما حُجب عنه في
    الصفحة. وقد وقع نظيرُه أمسِ في شاشة المزاد — `?export=xlsx` كان يُنزّل
    «سعر الوقوف» لمن لا ترد العبارةُ في صفحته إطلاقاً.

    و`columns` ثلاثيّاتٌ `(عنوان, دالّة, قدرة)` — والقدرةُ `None` لما لا يُحجب.
    ثلاثيّةٌ واحدةٌ لا قائمتان متوازيتان: قائمةُ عناوينَ وقائمةُ خلايا تتفارقان
    عند أوّل حذفٍ مشروط، فيخرج الملفُّ بعنوانٍ فوق خليّةِ غيره — وهو خطأٌ لا
    يُرى إلّا بفتح الملفّ.
    """
    allowed = {MONEY: seen.money, CUSTOMER: seen.customer}
    return [
        (header, getter)
        for header, getter, need in columns
        if need is None or allowed.get(need, False)
    ]


