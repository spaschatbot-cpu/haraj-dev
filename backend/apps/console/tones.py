"""لونُ الحالة، في مكانٍ واحد. T828.

الحالةُ كانت نصّاً عارياً في خانةِ جدول — «فشلت»، «منتهٍ»، «مُلغى» — فتُقرأ
صفّاً صفّاً. والحبّة الملوّنة تُمسح بالعين: من يفتح سجلّ الدفعات يبحث عن
الأحمر، ولا يقرأ ستّة صفوفٍ ليجد صفّاً.

**واللون لا يحمل المعنى وحده.** الكلمة داخل الحبّة دائماً، فمن لا يميّز الأحمر
من الأخضر يقرأ الجملة نفسها — وهي القاعدة التي يفرضها ``_stat.html`` على
الدلتا منذ T822، ولا سبب لأن تختلف هنا.

لماذا خريطةٌ واحدة لا سطرٌ في كل شاشة
=====================================
لأن ``paid`` تعني «مسدَّدة» في الفاتورة و«مدفوعة» في المركبة، و``cancelled``
تعني الشيء نفسه في ثلاثة نماذج. سطرٌ في كل قالبٍ يعني أن المُلغى أحمر في شاشةٍ
ورمادي في أخرى، وأن الموظّف الذي تعلّم اللون في شاشةٍ يُخطئ قراءته في التالية.

وقيمُ الحالات لا تتصادم بين النماذج: ``draft`` واحدة في المزاد والمركبة
والفاتورة، ولها المعنى نفسه — «لم يبدأ بعد» — فخريطةٌ بالقيمة تكفي، ولا حاجة
إلى مفتاحٍ مركّب من اسم النموذج. و``test_tones.py`` يثبت أن كل قيمةٍ في كل
تعداد لها صفٌّ هنا، فحالةٌ جديدة تُضاف غداً تُسقط الحزمة بدل أن تُرسَم رمادية
بلا أن ينتبه أحد.

النغمات الستّ
=============
* ``ok``      — انتهى إلى ما يُراد: مسدَّدة، وصل، رسا، سُوّي.
* ``bad``     — انتهى إلى ما لا يُراد: فشل، أُلغي، رُفض.
* ``warn``    — معلّق ينتظر أحداً: مفتوحة، جزئية، بانتظار قرار.
* ``info``    — جارٍ الآن: مباشر، تحت المزايدة، أُرسل.
* ``auction`` — حالةُ عرضٍ في المزاد: معروضة، أُعيد عرضها.
* (بلا نغمة) — محايد رمادي: مسودّة، وما لم يُصنَّف.
"""

from __future__ import annotations

#: الحالة إلى نغمتها. القيم من `AuctionState` و`VehicleState` و`InvoiceState`
#: و`PaymentIntentState` و`DeliveryState` و`InboundState`.
TONES: dict[str, str] = {
    # -- مسودّاتٌ وما لم يبدأ: محايد، فلا نغمة ---------------------------
    "draft": "",
    "queued": "",
    "received": "",
    "ignored": "",
    "withdrawn": "",
    # -- جارٍ الآن -------------------------------------------------------
    "live": "info",
    "bidding": "info",
    "sent": "info",
    "scheduled": "info",
    "pending": "warn",
    # -- معروضٌ في مزاد --------------------------------------------------
    "listed": "auction",
    "relisted": "auction",
    # -- معلّقٌ ينتظر أحداً ----------------------------------------------
    "open": "warn",
    "partial": "warn",
    "awaiting_decision": "warn",
    "invoiced": "warn",
    # -- انتهى إلى ما يُراد ----------------------------------------------
    "paid": "ok",
    "settled": "ok",
    "awarded": "ok",
    "released": "ok",
    "delivered": "ok",
    "succeeded": "ok",
    "processed": "ok",
    "ended": "ok",
    # -- انتهى إلى ما لا يُراد -------------------------------------------
    "cancelled": "bad",
    "rejected": "bad",
    "failed": "bad",
    "expired": "bad",
    "disputed": "bad",
    "rejected_signature": "bad",
}


def tone_of(state: str) -> str:
    """نغمةُ هذه الحالة، أو المحايد لما لا صفَّ له.

    لا ترمي على المجهول: شاشةٌ تنهار لأن حالةً جديدة أُضيفت إلى تعدادٍ أسوأ من
    حبّةٍ رمادية. و`test_tones.py` هو الذي يمنع المجهول من الوصول إلى هنا
    أصلاً — بالحزمة، لا بطلبٍ من مستخدم.
    """
    return TONES.get(state or "", "")


def with_tones(rows, field: str = "state"):
    """علّق `tone` على كل صفٍّ في هذه الصفحة، وأعِدها.

    على صفوف **الصفحة** لا على الاستعلام كلّه: صفحةٌ من خمسين لا تحتاج نغمة
    خمسة آلاف. وتُنادى من العرض لا من القالب — قالبٌ يحسب نغمةً هو مكانٌ ثانٍ
    للقاعدة ولا يُختبَر (المادة ٤-٤).
    """
    for row in rows:
        row.tone = tone_of(getattr(row, field, ""))
    return rows
