"""فحوصُ النشر التي يملكها هذا التطبيق: **أودو مُفعَّلٌ وأعمى**.

فحصُ نظامٍ لا `raise` عند الاستيراد، للسبب الذي تقوله `apps.accounts.checks`:
`settings/test.py` يرث `prod.py` عمداً، وحارسٌ عند الاستيراد هناك يمنع تحميل
إعدادات الاختبار أصلاً. و`manage.py check --deploy` حاجزٌ قائمٌ في خطوة النشر،
فما يُكتب هنا يصل البوّابة نفسَها التي تصلها فحوصُ جانغو.

## ما هذه الفحوص عنه

**التكاملُ المُطفأ عمداً ليس عطلاً.** `ODOO_ENABLED=False` هو الوضعُ الصحيح في
كل بيئةٍ لم يُدخلها مشغّلٌ إلى الدفتر الحقيقيّ، ولا يُنبَّه عليه بحرف.

العطلُ هو **المُفعَّلُ الأعمى**: بيئةٌ أعلنت `ODOO_ENABLED=True` وينقصها ما
يجعل الإعلانَ صحيحاً. وهي الحالةُ التي مرّت من كل شيءٍ حتى اليوم — مقيسةٌ في
`docs/environment-contract.md` §٤: أودو مُفعَّلٌ **بلا عنوانٍ ولا مفتاحٍ ولا سرِّ
ويبهوك** يعطي `check --deploy` رمزَ خروجٍ **صفراً**. وفرقُ الدرجتين هو متى
تعرف: الإقلاعُ الساقط يُكتشف في الثانية الأولى، والتكاملُ الأعمى بعد أسبوعٍ حين
يسأل محاسبٌ عن فواتيرَ لم تصل — وكلُّ رسالةٍ في الطابور تكون قد صُفَّت في
الصادر وفشلت بصمت.

ولذلك تسمّي كلُّ رسالةٍ هنا **المتغيّرَ بالاسم وما يحدث بدونه**: «إعدادٌ ناقص»
جملةٌ لا تُصلح شيئاً عند الثالثة فجراً.
"""

from __future__ import annotations

from django.conf import settings
from django.core.checks import Error, Tags, register


def _is_set(name: str) -> bool:
    """هل لهذا الإعداد قيمةٌ فعليّة؟ والفراغُ بعد `strip` ليس قيمة.

    مسافةٌ وحدها في ملفّ بيئة تمرّ من `if not value` في كل مكانٍ آخر، وهي
    بالضبط ما يكتبه من نسخ سطراً ولصقه.
    """
    return bool(str(getattr(settings, name, "") or "").strip())


@register(Tags.security, deploy=True)
def odoo_is_configured_when_it_is_enabled(app_configs, **kwargs) -> list:
    """أودو أعلن أنه شغّال — فليكن معه ما يجعله شغّالاً.

    الأربعةُ كلُّها `Error` لا `Warning`: ليس فيها «يعمل ناقصاً». بلا عنوانٍ لا
    يخرج نداءٌ واحد، وبلا مفتاحٍ يردّ الطرفُ الآخر 401، وبلا سرِّ ويبهوك تُرفض
    كلُّ رسالةٍ واردة، وبلا اسمِ قاعدةٍ يُقبل في الإنتاج ما أرسلته بيئةُ تجريب.
    """
    if not getattr(settings, "ODOO_ENABLED", False):
        # مطفأٌ عمداً. ولا كلمة.
        return []

    findings: list = []

    if not _is_set("ODOO_BASE_URL"):
        findings.append(
            Error(
                "أودو مُفعَّل (`ODOO_ENABLED=True`) و`ODOO_BASE_URL` فارغ.",
                hint="كلُّ نداءٍ سيذهب إلى `/endpoint` بلا مضيف فيفشل فوراً: "
                "الفواتيرُ والاستردادات تُصفّ في الصادر ولا تصل أودو أبداً، "
                "ولا شيءَ في الشاشة يقول ذلك. اضبطه على أصل أودو "
                "(`https://…odoo.com`) أو أطفئ التكامل بـ`ODOO_ENABLED=False`.",
                id="odoo.E001",
            )
        )

    if not _is_set("ODOO_API_KEY"):
        findings.append(
            Error(
                "أودو مُفعَّل و`ODOO_API_KEY` فارغ.",
                hint="ترويسةُ `Authorization` تخرج فارغة، فيردّ أودو 401 على كل "
                "رسالة ويتراكم الطابور بلا أن يُرسَل شيء. وهو سرٌّ يوضع في "
                "البيئة ولا يُودَع في الكود.",
                id="odoo.E002",
            )
        )

    if not _is_set("ODOO_WEBHOOK_SECRET"):
        findings.append(
            Error(
                "أودو مُفعَّل و`ODOO_WEBHOOK_SECRET` فارغ.",
                hint="كلُّ رسالةٍ واردةٍ من أودو تُرفض («لا يوجد سرّ ويبهوك "
                "مضبوط») — وهو الرفضُ الآمن، لكنه يعني أن لا تأكيدَ دفعٍ ولا "
                "ردَّ فاتورةٍ يصل هذا النظام إطلاقاً. اتّجاهان للتكامل، "
                "وهذا هو الوارد.",
                id="odoo.E003",
            )
        )

    if not _is_set("ODOO_DB"):
        findings.append(
            Error(
                "أودو مُفعَّل و`ODOO_DB` فارغ.",
                hint="حارسُ «رسالةٌ من قاعدةٍ أجنبيّة» في `apps/odoo/views.py` "
                "يُطفأ حين لا تُسمّى القاعدة: رسالةٌ من بيئة تجريب أودو "
                "تُقبَل في الإنتاج وتُقيَّد في الدفتر الحقيقيّ. اسمُ القاعدة "
                "هو ما يفرّق بين النظامين.",
                id="odoo.E004",
            )
        )

    return findings


@register(Tags.security, deploy=True)
def odoo_transport_and_journal_are_declared(app_configs, **kwargs) -> list:
    """اثنتان تعملان — وقد تعملان في المكان الخطأ.

    فُصلتا عن الفحص أعلاه لأن درجتَهما أخرى: هناك «لن يعمل أبداً»، وهنا «يعمل،
    وربّما ضدَّك». وتُقرآن في بيئةٍ منشورةٍ وحدها؛ على جهاز تطوير كلاهما وضعٌ
    مقبولٌ ومكتوبٌ في `settings/dev.py`.
    """
    if settings.DEBUG:
        return []

    findings: list = []

    if getattr(settings, "ODOO_INSECURE_TLS", False):
        findings.append(
            Error(
                "`ODOO_INSECURE_TLS=True` في بيئةٍ منشورة: التحقّقُ من شهادة "
                "أودو مُطفأ.",
                hint="مفتاحُ الـAPI والفواتيرُ تمرّ في قناةٍ لا يُتحقَّق من "
                "طرفها الآخر — أي أن اعتراضَها لا يحتاج أكثر من الوقوف في "
                "الطريق. الإطفاءُ لأجهزة التطوير وحدها (شهادتُها قديمةٌ "
                "غالباً، كـ v1).",
                id="odoo.E005",
            )
        )

    # **حُذف الافتراضيُّ من `base.py`** بقرار المالك ٢٠٢٦-٠٩-١٤، فلم تعد ثمّة
    # وراثةٌ صامتة: إمّا كُتب الدفترُ بقرار، أو لا دفترَ أصلاً. ولذلك صار خطأً
    # لا تحذيراً، وسقطت معه `odoo.W001` — كانت تقول «ورثتَ `005/01`» وهي جملةٌ
    # لم يعد لها مصداق.
    #
    # ولماذا الرفضُ عند الإقلاع لا عند أوّل دفعة: نداءٌ بدفترٍ خاطئ **لا يردّه
    # أودو** — يقبله ويُقيّده في الحساب الخطأ، فلا استثناءَ ولا شاشةَ تشكو،
    # ويُكتشف من محاسبٍ يسأل بعد شهر. فالإقلاعُ هو اللحظةُ الوحيدة التي نملك
    # فيها أن نمنعه، قبل أن يتحرّك ريالٌ واحد.
    if getattr(settings, "ODOO_ENABLED", False) and not _is_set("ODOO_PAYMENT_CODE"):
        findings.append(
            Error(
                "أودو مُفعَّلٌ و`ODOO_PAYMENT_CODE` فارغ.",
                hint="وهو **دفترُ اليوميّة عند أودو** لا رقمٌ داخليّ: بلا قيمةٍ "
                "صحيحةٍ تُقيَّد كلُّ دفعةٍ واستردادٍ في الحساب الخطأ، **ويُقبل "
                "النداءُ ولا يُرفض**. وv1 يستعمل `005/01` للفواتير و`0002/02` "
                "للاشتراكات — والقيمةُ تُكتب بقرارِ من يعرف دفاترَ المحاسبة، لا "
                "تُورَث من الشيفرة.",
                id="odoo.E006",
            )
        )

    return findings
