#: يملك الخادم. لكنّ سيرفرَ التجربة **لا مزوّدَ رسائلَ له ولا يُفترض أن يكون**
#: — لا نشتري رسائلَ لاختبار، ولا نضع مفاتيحَ المزوّد الحقيقيّ على آلةٍ بلا
#: تشفير. وطباعةُ الرمز في السجلّ هي الوسيلةُ المقصودة للدخول هنا.
