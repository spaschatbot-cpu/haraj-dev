"""سيرفرُ تجربةٍ على الإنترنت، بلا شهادةِ تشفيرٍ بعد.

**لماذا ملفٌّ ثالث ولم يكفِ الاثنان.** بين `dev` و`prod` فجوةٌ لا يسدّها أحدهما:

* `dev` فيها ``DEBUG = True`` و``ALLOWED_HOSTS`` محصورةٌ في `localhost`. فهي
  لا تُقلع على عنوانٍ عامّ أصلاً، ولو أُجبرت لأظهرت صفحةَ خطأِ جانغو — بمسارات
  الملفّات وقيم الإعدادات — **لكلّ من يفتح الرابط**.
* `prod` فيها ``SECURE_SSL_REDIRECT = True`` وكعكاتٌ ``Secure``. وبلا شهادةٍ
  يعني ذلك شيئين: تحويلٌ لا نهائيّ إلى ``https://`` لا أحد يردّ عليه، وكعكةُ
  جلسةٍ لا يرسلها المتصفّح على HTTP — **فالدخولُ يبدو ناجحاً ثم يعود إلى
  شاشة الدخول** بلا رسالة، وهو عطلٌ يُطارَد ساعاتٍ لأنه لا يُشبه سببَه.

فهذا الملفُّ يرث `prod` كاملةً — ``DEBUG = False`` وكلُّ حرّاس الإقلاع — ويفكّ
**ما يتطلّب TLS وحده**، لا أكثر.

خطرٌ يُقال كما هو
=================
بلا تشفير، كلمةُ مرور الموظّف تسافر **نصّاً واضحاً** على الشبكة، وكذلك كعكةُ
جلسته. هذه الحالةُ مقبولةٌ لأيّامٍ على بياناتٍ تجريبيّة، **وغيرُ مقبولةٍ على
بياناتِ عملاءَ حقيقيّة**. والمخرجُ ليس تعديلاً هنا بل شهادةٌ مجّانيّة
(Let's Encrypt) ثم ``DJANGO_SETTINGS_MODULE=config.settings.prod``.

ولذلك **لا افتراضيَّ صامتاً**: ``ALLOWED_HOSTS`` تأتي من البيئة كما في `prod`،
ومن يشغّل هذا الملفَّ يكتب اسمَه في `.env` بيده — فلا أحدَ يقع فيه بالخطأ وهو
يظنّ أنه في الإنتاج.
"""

from .prod import *  # noqa: F403

ENVIRONMENT_NAME = env("ENVIRONMENT_NAME", default="staging")  # noqa: F405

# ---------------------------------------------------------------------------
# ما يُفكّ، ولا شيء غيره: كلُّ سطرٍ هنا يلزمه TLS ليعمل، وليس تخفيفاً اختيارياً.
# ---------------------------------------------------------------------------

#: تحويلُ كلِّ طلبٍ إلى `https://` بلا شهادةٍ = حلقةٌ لا تنتهي.
SECURE_SSL_REDIRECT = False

#: و`HSTS` أخطرُ من الحلقة: ترويسةٌ **يحفظها المتصفّحُ شهوراً** فيرفض بعدها
#: فتحَ هذا المضيف على HTTP حتى لو أُطفئت هنا. إطلاقُها من عنوانٍ بلا شهادة
#: يُقفل العنوانَ على كلّ من فتحه مرّةً، ولا يُفكّ إلا بمسح إعدادات المتصفّح.
SECURE_HSTS_SECONDS = 0
SECURE_HSTS_INCLUDE_SUBDOMAINS = False
SECURE_HSTS_PRELOAD = False

#: كعكةٌ `Secure` لا يرسلها المتصفّحُ على HTTP — فالجلسةُ تُكتب ولا تعود،
#: والدخولُ يدور في محلّه. و`HttpOnly` و`SameSite` يبقيان كما في `prod`:
#: لا علاقةَ لهما بالتشفير.
SESSION_COOKIE_SECURE = False
CSRF_COOKIE_SECURE = False

# ---------------------------------------------------------------------------
# حارسٌ واحدٌ يُسكَت، وبسببٍ مكتوب
# ---------------------------------------------------------------------------

